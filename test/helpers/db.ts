import { PGlite } from "@electric-sql/pglite";
import { drizzle } from "drizzle-orm/pglite";
import { migrate } from "drizzle-orm/pglite/migrator";
import { fileURLToPath } from "node:url";
import * as schema from "../../db/schema.ts";
import { setDbForTesting } from "../../db/index.ts";

export const MIGRATIONS_FOLDER = fileURLToPath(new URL("../../db/migrations", import.meta.url));

/** In-memory Postgres (PGlite) se všemi migracemi — žádná externí DB. */
export async function setupTestDb() {
  const client = new PGlite();
  const db = drizzle(client, { schema });
  await migrate(db, { migrationsFolder: MIGRATIONS_FOLDER });
  setDbForTesting(db as never);
  return {
    db,
    client,
    async close() {
      setDbForTesting(null);
      await client.close();
    },
  };
}

let ipCounter = 0;

/** Každý test dostane jinou IP, aby se rate limity testů neovlivňovaly. */
export function uniqueIp(): string {
  ipCounter++;
  return `203.0.113.${ipCounter % 250}:${ipCounter}`;
}

export function jsonRequest(path: string, method: string, body?: unknown, ip = uniqueIp()): Request {
  return new Request(`http://localhost${path}`, {
    method,
    headers: { "content-type": "application/json", "x-forwarded-for": ip },
    body: body === undefined ? undefined : JSON.stringify(body),
  });
}

export function routeParams<T extends Record<string, string>>(params: T) {
  return { params: Promise.resolve(params) };
}

